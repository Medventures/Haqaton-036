// ---------- Поиск (русский + казахский) ----------

// Казахские буквы приводим к русским аналогам: так «кенес» найдёт «кеңес», а
// латинская i (частая замена «і» на русской раскладке) — «и».
const KK_FOLD: Record<string, string> = { ә: 'а', ғ: 'г', қ: 'к', ң: 'н', ө: 'о', ұ: 'у', ү: 'у', һ: 'х', і: 'и', ё: 'е', i: 'и' };
export const normalizeQuery = (s: string) => s.toLowerCase().replace(/[әғқңөұүһіёi]/g, c => KK_FOLD[c] ?? c);

const WORD = /[^а-яa-z0-9]+/;
const LETTER = /[а-яa-z0-9]/;
// Упрощённый стемминг: отсекаем окончания, чтобы «анализы/анализа» совпадали.
const stem = (w: string) => w.slice(0, Math.max(4, Math.min(w.length, 6)));
const wordsOf = (normalized: string) => normalized.split(WORD).filter(w => w.length > 2).map(stem);

/** Совпадение ключевого слова: короткие (≤2) — только целым словом, из 3 букв — с начала слова. */
function hasKeyword(q: string, k: string): boolean {
  if (k.length > 3) return q.includes(k);
  for (let i = q.indexOf(k); i >= 0; i = q.indexOf(k, i + 1)) {
    const startOk = i === 0 || !LETTER.test(q[i - 1]);
    const endOk = k.length > 2 || i + k.length >= q.length || !LETTER.test(q[i + k.length]);
    if (startOk && endOk) return true;
  }
  return false;
}

const INDEX = KNOWLEDGE.map(card => {
  const kk = KNOWLEDGE_KK[card.id];
  return {
    card,
    keywords: [...new Set([...card.keywords, ...(kk?.keywords ?? [])].map(normalizeQuery))],
    titleWords: new Set([...wordsOf(normalizeQuery(card.title)), ...(kk ? wordsOf(normalizeQuery(kk.title)) : [])]),
  };
});

/** Поиск по базе знаний. Учитывает русские и казахские ключевые слова; карточки возвращаются на языке lang. */
export function retrieve(query: string, limit = 2, lang: Lang = 'ru'): { card: KnowledgeCard; score: number }[] {
  const q = normalizeQuery(query);
  const words = wordsOf(q);
  const scored = INDEX.map(({ card, keywords, titleWords }) => {
    let score = 0;
    for (const k of keywords) if (hasKeyword(q, k)) score += 3;
    for (const w of words) if (titleWords.has(w)) score += 1;
    return { card, score };
  });
  return scored.filter(s => s.score >= 3).sort((a, b) => b.score - a.score).slice(0, limit).map(s => ({ card: cardIn(s.card, lang), score: s.score }));
}

/** Карточка на нужном языке (id и версия те же). */
export function cardIn(card: KnowledgeCard, lang: Lang): KnowledgeCard {
  const ru = KNOWLEDGE.find(k => k.id === card.id) ?? card;
  const kk = lang === 'kk' ? KNOWLEDGE_KK[card.id] : undefined;
  return kk ? { ...ru, title: kk.title, answer: kk.answer, keywords: kk.keywords } : ru;
}

/** Вся база знаний на нужном языке (например, для контекста разговорного агента). */
export function knowledgeIn(lang: Lang): KnowledgeCard[] {
  return KNOWLEDGE.map(card => cardIn(card, lang));
}
