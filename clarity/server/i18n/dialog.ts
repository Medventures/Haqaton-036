const TZ = 'Asia/Almaty';

export const fmtDateTime = (iso: string, lang: Lang) => new Date(iso).toLocaleString(LOCALE[lang], { timeZone: TZ, weekday: 'long', day: 'numeric', month: 'long', hour: '2-digit', minute: '2-digit' });
export const fmtShort = (iso: string, lang: Lang) => new Date(iso).toLocaleString(LOCALE[lang], { timeZone: TZ, day: 'numeric', month: 'short', hour: '2-digit', minute: '2-digit' });
export const fmtStamp = (iso: string, lang: Lang) => new Date(iso).toLocaleString(LOCALE[lang], { timeZone: TZ });

/** Имя ассистента на языке пациента. */
export const assistantName = (avatar: AvatarId | undefined, lang: Lang) => pick(AVATAR_NAME[avatar ?? 'aruzhan'], lang);

/** Строчная первая буква, но аббревиатуры («ИКД», «СКФ») не трогаем. */
export const lcFirst = (s: string) => (s.length > 1 && s[1] === s[1].toUpperCase() && s[1] !== s[1].toLowerCase() ? s : s.charAt(0).toLowerCase() + s.slice(1));

// Казахский дательный падеж специальности: «неврологқа жазылу».
const SPEC_DATIVE_KK: Record<string, string> = {
  'Невролог': 'Неврологқа', 'Нейрохирург': 'Нейрохирургқа', 'Онколог': 'Онкологқа', 'Эндокринолог': 'Эндокринологқа', 'ЛОР-врач': 'ЛОР-дәрігерге',
  'Терапевт': 'Терапевтке', 'Нефролог': 'Нефрологқа',
};
// Русский дательный падеж: «записать к неврологу».
const SPEC_DATIVE_RU: Record<string, string> = {
  'Невролог': 'неврологу', 'Нейрохирург': 'нейрохирургу', 'Онколог': 'онкологу', 'Эндокринолог': 'эндокринологу', 'ЛОР-врач': 'ЛОР-врачу',
  'Терапевт': 'терапевту', 'Нефролог': 'нефрологу',
};

/** Специальность в дательном падеже внутри фразы: «к неврологу» / «неврологқа». */
export const specDative = (spec: string, lang: Lang) =>
  lang === 'kk'
    ? (SPEC_DATIVE_KK[spec] ? lcFirst(SPEC_DATIVE_KK[spec]) : `маманға (${specialtyLabel(spec, 'kk')})`)
    : (SPEC_DATIVE_RU[spec] ?? `специалисту (${spec.toLowerCase()})`);

// ---- Даты пошаговой инструкции (Алматы, UTC+5, без перехода на летнее время) ----
const MONTHS_RU = ['января', 'февраля', 'марта', 'апреля', 'мая', 'июня', 'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря'];
const MONTHS_KK = ['қаңтар', 'ақпан', 'наурыз', 'сәуір', 'мамыр', 'маусым', 'шілде', 'тамыз', 'қыркүйек', 'қазан', 'қараша', 'желтоқсан'];
const MONTHS_KK_DAT = ['қаңтарға', 'ақпанға', 'наурызға', 'сәуірге', 'мамырға', 'маусымға', 'шілдеге', 'тамызға', 'қыркүйекке', 'қазанға', 'қарашаға', 'желтоқсанға'];
const almaty = (iso: string | Date) => new Date(new Date(iso).getTime() + 5 * 3_600_000);
/** «4 октября» / «4 қазан». */
export const fmtDay = (iso: string | Date, lang: Lang) => { const d = almaty(iso); return `${d.getUTCDate()} ${(lang === 'kk' ? MONTHS_KK : MONTHS_RU)[d.getUTCMonth()]}`; };
/** Казахский дательный падеж даты: «4 қазанға (дейін)». */
export const fmtDayDat = (iso: string | Date) => { const d = almaty(iso); return `${d.getUTCDate()} ${MONTHS_KK_DAT[d.getUTCMonth()]}`; };
/** «11:30» по Алматы. */
export const fmtTime = (iso: string | Date) => { const d = almaty(iso); return `${String(d.getUTCHours()).padStart(2, '0')}:${String(d.getUTCMinutes()).padStart(2, '0')}`; };
/** Календарная дата по Алматы «YYYY-MM-DD» (для сравнения дней). */
export const almatyDate = (iso: string | Date) => almaty(iso).toISOString().slice(0, 10);

/** Специальность в тексте реплики: по-русски строчными (как было), по-казахски — отображаемое название. */
export const specText = (spec: string | undefined, lang: Lang) => {
  const s = spec || 'Невролог';
  return lang === 'kk' ? specialtyLabel(s, 'kk') : s.toLowerCase();
};

/** «Невролог (демо) — А. Сапарова» → «ЛОР-дәрігер (демо) — …» для казахского. */
export const doctorLabel = (doctor: string, lang: Lang) =>
  lang === 'kk' ? doctor.replace(/^(.+?) \(демо\)/, (_m, s: string) => `${specialtyLabel(s.trim(), 'kk')} (демо)`) : doctor;

