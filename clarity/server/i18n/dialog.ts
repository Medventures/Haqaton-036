// Казахская версия типизирована как русская: ни один ключ не может отсутствовать.
// Тексты для персонала (задачи координатора, причины записи) остаются на русском
// и здесь не хранятся.
// Казахские формулировки — черновой перевод, требуют проверки редактором (docs/DECISIONS.md).

import { AVATAR_NAME, LOCALE, pick, specialtyLabel, type AvatarId, type Lang } from '../../shared/i18n';
