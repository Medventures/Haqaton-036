// В JS «\b» работает только для латиницы — заменяем на границу по любым буквам (кириллица, казахский).
const BOUND = '(?:(?<![\\p{L}\\p{N}])|(?![\\p{L}\\p{N}]))';
for (const a of ANALYTES) a.re = new RegExp(a.re.source.replace(/\\b/g, BOUND), 'iu');

/** Показатели мочи и эритроцитарные индексы — не путать с показателями крови. */
const NOT_BLOOD_MAIN = new RegExp(String.raw`в моче|мочи(?![\p{L}])|несепте|urine|средн|ширин|распредел|индекс|(?<![\p{L}])(?:mch|mchc|mcv|rdw)(?![\p{L}])`, 'iu');

export const analyteByCode = (code: string | undefined) => (code ? ANALYTES.find(a => a.code === code) : undefined);

/** Найти показатель справочника по названию из бланка. */
export function matchAnalyte(name: string): Analyte | undefined {
  const n = name.trim();
  if (!n || NOT_BLOOD_MAIN.test(n)) return undefined;
  return ANALYTES.find(a => a.re.test(n));
}

const U = (unit: string | undefined) => (unit ?? '').toLowerCase().replace(/\s+/g, '').replace(/μ/g, 'µ');

/**
 * Значение в канонических единицах справочника (для критических порогов и МРТ).
 * undefined — единицы непонятны, пересчёт ненадёжен.
 */
export function canonicalValue(code: string | undefined, value: number | null | undefined, unit?: string): number | undefined {
  if (value === null || value === undefined || !Number.isFinite(value)) return undefined;
  const u = U(unit);
  const mgdl = /мг\/дл|mg\/dl|мг%|mg%/.test(u);
  switch (code) {
    case 'creatinine':
      if (mgdl) return Math.round(value * 88.4);
      if (/ммоль|mmol/.test(u) && !/мкмоль|µmol|umol|mkmol/.test(u)) return Math.round(value * 1000);
      if (/мкмоль|µmol|umol|mkmol|мкм/.test(u)) return value;
      if (!u) return value < 20 ? Math.round(value * 88.4) : value; // без единиц: <20 — вероятно мг/дл
      return undefined;
    case 'glucose':
      if (mgdl) return Math.round((value / 18) * 10) / 10;
      if (!u) return value > 40 ? Math.round((value / 18) * 10) / 10 : value;
      if (/ммоль|mmol/.test(u)) return value;
      return undefined;
    case 'hgb':
      if (/г\/дл|g\/dl/.test(u)) return value * 10;
      if (/г\/л|g\/l/.test(u)) return value;
      if (!u) return value < 25 ? value * 10 : value;
      return undefined;
    case 'potassium':
    case 'sodium':
      if (!u || /ммоль|mmol|мэкв|meq/.test(u)) return value;
      return undefined;
    case 'plt':
      if (value > 5000) return Math.round(value / 1000); // абсолютное число в мкл
      return value;
    default:
      return value;
  }
}
