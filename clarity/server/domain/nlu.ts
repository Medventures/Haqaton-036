// Разбор свободного текста без LLM (русский и казахский). Используется всегда первым;
// LLM подключается только если правила не распознали намерение.
// Оба языка распознаются всегда, независимо от выбранного: пациенты часто смешивают
// русский и казахский в одной реплике.

import type { Answer } from '../../shared/types';
import type { Lang } from '../../shared/i18n';

const norm = (t: string) => t.toLowerCase().replace(/ё/g, 'е').replace(/[!?.,;:()«»"]/g, ' ').replace(/\s+/g, ' ').trim();

// Казахские буквы → ближайшие русские. Многие пишут без казахской раскладки
// («жок», «бiлмеймiн» с латинской i), поэтому казахские шаблоны сравниваются
// со «свёрнутым» текстом, а сами шаблоны пишутся с настоящими казахскими буквами.
const FOLD: Record<string, string> = { ә: 'а', ғ: 'г', қ: 'к', ң: 'н', ө: 'о', ұ: 'у', ү: 'у', һ: 'х', і: 'и', i: 'и' };
export const foldKk = (t: string) => t.replace(/[әғқңөұүһіi]/g, c => FOLD[c] ?? c);
/** Казахский шаблон: исходник сворачивается так же, как текст. */
const kk = (re: RegExp) => new RegExp(foldKk(re.source), re.flags);
/** Нормализованный и свёрнутый текст для казахских шаблонов. */
const kkNorm = (t: string) => foldKk(norm(t));

// ---------------- Язык реплики ----------------

const KK_LETTER = /[әғқңөұүһі]/;
// Частые казахские слова без специфичных букв (в свёрнутом виде).
const KK_WORDS = new Set(['бар', 'жок', 'ия', 'иа', 'мен', 'сиз', 'сизге', 'сен', 'бола', 'болады', 'ма', 'ме', 'ба', 'бе', 'па', 'пе', 'керек', 'жане', 'туралы', 'ушин', 'калай', 'кашан', 'канша', 'неге', 'кайда', 'рахмет', 'жаксы', 'емес', 'деп', 'бир', 'еки', 'жарайды', 'кун', 'бугин', 'кеше', 'апта', 'билмеймин', 'есимде', 'салем', 'салеметсиз', 'сауалнама', 'дайындык', 'корытынды', 'уйлестируши', 'дариги', 'дари', 'бурын', 'болган']);
const RU_WORDS = new Set(['и', 'в', 'во', 'не', 'на', 'что', 'это', 'я', 'у', 'меня', 'мне', 'как', 'можно', 'да', 'нет', 'есть', 'если', 'или', 'по', 'для', 'с', 'со', 'до', 'после', 'когда', 'где', 'почему', 'вы', 'ли', 'очень', 'уже', 'еще', 'только', 'был', 'была', 'было', 'так', 'все', 'мой', 'моя', 'его', 'она', 'он', 'они', 'мы', 'вас', 'вам', 'ваш', 'нужно', 'надо', 'хочу', 'знаю', 'спасибо', 'здравствуйте', 'привет', 'пожалуйста', 'помню', 'будет', 'сколько', 'зачем', 'могу', 'же', 'бы', 'от', 'за', 'из', 'к', 'о']);

/**
 * Язык реплики по признакам: казахские буквы и частые слова против русских служебных слов.
 * null — признаков нет или поровну (имя, число, «ок»).
 */
export function detectLang(text: string): Lang | null {
  let kkScore = 0;
  let ruScore = 0;
  for (const raw of text.toLowerCase().split(/[^a-zа-яёәғқңөұүһіi-]+/)) {
    const w = raw.replace(/^-+|-+$/g, '');
    if (!w) continue;
    if (KK_LETTER.test(w)) { kkScore += 2; continue; }
    if (KK_WORDS.has(foldKk(w))) kkScore += 1;
    if (RU_WORDS.has(w.replace(/ё/g, 'е'))) ruScore += 1;
    if (/[ёъщ]/.test(w)) ruScore += 1;
  }
  if (kkScore > ruScore) return 'kk';
  if (ruScore > kkScore) return 'ru';
  return null;
}

// ---------------- Да / нет / не знаю ----------------

const UNKNOWN = /(?:^|\s)(?:не знаю|не помню|не уверен\S*|затрудняюсь|без понятия|хз|возможно|может быть|наверное|не могу сказать)(?:\s|$)/;
const NO = /^(?:нет|неа|не-а|нету|no|никогда|не было|не бывает|не имеется|отсутствует|ни разу|нет конечно|конечно нет)(?:\s|$)|(?:^|\s)(?:нет|никогда|не было)(?:\s|$)/;
const YES = /^(?:да|ага|угу|yes|есть|имеется|был[аио]?|бывает|конечно|верно|так точно|ну да|да есть)(?:\s|$)|(?:^|\s)(?:да|есть|имеется)(?:\s|$)/;

// «мүмкін емес» (невозможно) — это «нет», хотя «мүмкін» (возможно) — «не знаю».
const KK_IMPOSSIBLE = kk(/(?:^|\s)мүмкін емес(?:\s|$)/);
// «есімде жоқ» содержит «жоқ», поэтому «не знаю» проверяется раньше «нет».
const KK_UNKNOWN = kk(/(?:^|\s)(?:білмей\S*|білмедім|есім\S* (?:жоқ|қалма\S*|емес)|есте жоқ|сенімді емес\S*|сенімсіз\S*|анық емес|нақты емес|мүмкін|шамасы|бәлкім|айта алмаймын|белгісіз|кім біледі)(?:\s|$)/);
// Отрицания: «жоқ», «болған жоқ», «ешқашан», «емес», глаголы с отрицанием (-маймын, -маған).
const KK_NO = kk(/(?:^|\s)(?:жоқ\S*|ешқашан|ешқандай|болмаған\S*|болмады|емес\S*|\S{2,}(?:ма|ме|ба|бе|па|пе)й(?:мын|мін)|\S{2,}(?:ма|ме|ба|бе|па|пе)(?:ған|ген)\S*|\S{2,}(?:ма|ме|ба|бе|па|пе)(?:дым|дім|тым|тім))(?:\s|$)/);
const KK_YES = kk(/(?:^|\s)(?:иә|ия|иа|әрине|бар|бармын|болған\S*|болды|болатын|солай|дұрыс|рас|жарайды|келісемін|мақұл)(?:\s|$)/);
// «Сұрағым бар» — это не ответ «да» на вопрос анкеты.
const KK_HAS_QUESTION = kk(/(?:^|\s)(?:сұрағым|сұрақ|сауалым) бар/);

export function parseAnswer(text: string): Answer | null {
  const t = norm(text);
  if (!t) return null;
  if (UNKNOWN.test(t)) return 'unknown';
  const f = foldKk(t);
  if (KK_IMPOSSIBLE.test(f)) return 'no';
  if (KK_UNKNOWN.test(f)) return 'unknown';
  // «нет» проверяем раньше «да», чтобы «да нет» и «нет, не было» не стали «да»
  if (NO.test(t) || KK_NO.test(f)) return 'no';
  if (YES.test(t)) return 'yes';
  if (KK_YES.test(f) && !KK_HAS_QUESTION.test(f)) return 'yes';
  return null;
}

/** Креатинин: число в мкмоль/л; если похоже на мг/дл — конвертируем. */
export function parseCreatinine(text: string): number | null {
  const t = text.toLowerCase().replace(/(\d),(\d)/g, '$1.$2');
  const m = t.match(/(\d+(?:\.\d+)?)/);
  if (!m) return null;
  let v = parseFloat(m[1]);
  if (/мг|mg/.test(t) || v < 15) v = Math.round(v * 88.4); // мг/дл → мкмоль/л
  return Math.round(v);
}

// ---------------- Даты ----------------

const KK_NUM: Record<string, number> = { бир: 1, еки: 2, уш: 3, торт: 4, бес: 5, алты: 6, жети: 7, сегиз: 8, тогыз: 9, он: 10, жарты: 0.5 };
const KK_MONTHS = ['қаңтар', 'ақпан', 'наурыз', 'сәуір', 'мамыр', 'маусым', 'шілде', 'тамыз', 'қыркүйек', 'қазан', 'қараша', 'желтоқсан'].map(foldKk);
const RU_MONTHS = ['январ', 'феврал', 'март', 'апрел', 'ма[йя]', 'июн', 'июл', 'август', 'сентябр', 'октябр', 'ноябр', 'декабр'];
const KK_AGO = kk(/(?:^|\s)(\d+|бір|екі|үш|төрт|бес|алты|жеті|сегіз|тоғыз|он|жарты)?\s*(күн|апта|ай|жыл)\S*\s+(астам\s+)?(?:бұрын|болды|болған)/);

/**
 * Дата анализа: «12.09», «12.09.2026», «вчера», «неделю назад», «2 недели назад»;
 * по-казахски: «бүгін», «кеше», «алдыңғы күні», «5 күн бұрын», «бір апта бұрын», «12 қыркүйек».
 */
export function parseLabDate(text: string, now: Date): string | null {
  const t = norm(text);
  const iso = (d: Date) => `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
  const shift = (days: number) => { const d = new Date(now); d.setDate(d.getDate() - Math.round(days)); return iso(d); };
  if (/сегодня/.test(t)) return shift(0);
  if (/позавчера/.test(t)) return shift(2);
  if (/вчера/.test(t)) return shift(1);
  const ago = t.match(/(\d+|пару|неделю|месяц|полгода)\s*(дн|день|дня|недел|месяц|мес)?\S*\s*назад/);
  if (ago) {
    const n = ago[1] === 'пару' ? 2 : ago[1] === 'неделю' ? 7 : ago[1] === 'месяц' ? 30 : ago[1] === 'полгода' ? 180 : parseInt(ago[1], 10);
    const unit = ago[2] ?? (ago[1] === 'неделю' || ago[1] === 'месяц' || ago[1] === 'полгода' ? 'дн' : 'дн');
    const mult = unit.startsWith('недел') ? 7 : unit.startsWith('мес') ? 30 : 1;
    return shift(n * mult);
  }

  // Казахский
  const f = foldKk(t);
  if (/(?:^|\s)бугин/.test(f)) return shift(0);
  if (/алдынгы куни|бурнагы куни|кешеден бурын/.test(f)) return shift(2);
  if (/(?:^|\s)кеше(?:\s|$|ги)/.test(f)) return shift(1);
  const kkAgo = f.match(KK_AGO);
  if (kkAgo) {
    const n = kkAgo[1] ? (KK_NUM[kkAgo[1]] ?? parseInt(kkAgo[1], 10)) : 1;
    const mult = kkAgo[2] === 'апта' ? 7 : kkAgo[2] === 'ай' ? 30 : kkAgo[2] === 'жыл' ? 365 : 1;
    // «бір айдан астам бұрын» — больше месяца
    return shift(n * mult * (kkAgo[3] ? 1.5 : 1));
  }
  if (/откен апта/.test(f)) return shift(7);
  if (/откен ай/.test(f)) return shift(30);
  if (/(?:^|\s)осы апта/.test(f)) return shift(3);

  // «12 қыркүйек», «12-қыркүйекте», «12 сентября»
  const monthRe = new RegExp(`(\\d{1,2})[\\s-]*(${[...KK_MONTHS, ...RU_MONTHS].join('|')})\\S*(?:\\s+(\\d{4}))?`);
  const mm = f.match(monthRe);
  if (mm) {
    const idx = KK_MONTHS.findIndex(m => mm[2] === m);
    const month = idx >= 0 ? idx : RU_MONTHS.findIndex(m => new RegExp(`^${m}$`).test(mm[2]));
    if (month >= 0) {
      const day = +mm[1];
      let year = mm[3] ? +mm[3] : now.getFullYear();
      if (day >= 1 && day <= 31) {
        let d = new Date(year, month, day);
        if (!mm[3] && d > now) { year -= 1; d = new Date(year, month, day); }
        if (d <= now) return iso(d);
      }
    }
  }

  const dm = text.match(/(\d{1,2})[./-](\d{1,2})(?:[./-](\d{2,4}))?/);
  if (dm) {
    const day = +dm[1], month = +dm[2];
    let year = dm[3] ? +dm[3] : now.getFullYear();
    if (year < 100) year += 2000;
    if (day < 1 || day > 31 || month < 1 || month > 12) return null;
    let d = new Date(year, month - 1, day);
    if (!dm[3] && d > now) d = new Date(year - 1, month - 1, day);
    if (d > now) return null;
    return iso(d);
  }
  return null;
}

// ---------------- Намерения ----------------

export type Intent =
  | 'greeting' | 'screening' | 'prep' | 'reminder' | 'report' | 'booking'
  | 'human' | 'cancel' | 'confirm' | 'status' | 'thanks' | 'menu' | 'question' | 'unknown';

// [намерение, русский шаблон, казахский шаблон]. Порядок важен: первое совпадение побеждает.
const INTENTS: [Intent, RegExp, RegExp][] = [
  ['human', /(?:живо\S* человек|оператор|координатор|позвоните мне|перезвон|свяжите|администратор)/,
    kk(/(?:үйлестіруші|оператор|адаммен сөйлес|тірі адам|маманмен сөйлес|әкімші|маған қоңырау|маған хабарлас|хабарласыңызшы|қайта қоңырау)/)],
  ['cancel', /(?:отмен\S* (?:визит|запис|мрт|исследован)|не смогу прийти|не приду|перенест|перенос)/,
    kk(/(?:(?:уақыт|күн|жазылу|мрт|тексеру|визит|келу|қабылдау)\S*\s+(?:\S+\s+)?(?:ауыстыр|өзгерт|болдырма|кейінге|шегер)|^ауыстыр|кейінге қалдыр|кейінге шегер|келе алмай|бара алмай|келмеймін|бармаймын|басқа күнге|басқа уақытқа)/)],
  ['confirm', /(?:подтверж\S* (?:визит|запис)|приду|буду вовремя)/,
    kk(/(?:раста|(?<!(?:қашан|қайда|қалай|нешеде|қай уақытта) )келемін(?! бе)|(?<!(?:қашан|қайда|қалай|нешеде|қай уақытта) )барамын(?! ба)|уақытында кел|міндетті түрде кел)/)],
  ['report', /(?:заключени|расшифр|результат|описани\S* снимк|объясни\S* (?:что|текст))/,
    kk(/(?:қорытынды|(?:мәтін|нәтиже|сипаттама)\S* түсіндір)/)],
  ['booking', /(?:запиш|записать|консультац|к врачу|к неврологу|к специалисту|приём|прием)/,
    kk(/(?:неврологқа|нейрохирургқа|онкологқа|эндокринологқа|маманға|дәрігерге|кеңеске|кеңес ал|қабылдауға|жазылғым|жазылайын|жазылсам|жазылуға|жазылу керек|жазып қой|жазып бер|жазыңыз)/)],
  ['reminder', /(?:напомин|напомни|уведомлен)/,
    kk(/(?:еске сал|еске түсір|ескерт|хабарландыру|хабарлама)/)],
  ['prep', /(?:подготов|что взять|что с собой|инструкц|памятк|чек-?лист|как готовиться)/,
    kk(/(?:дайында|дайындық|дайындығ|не алып кел|не ала кел|не алу керек|өзіммен не|нұсқаулы[қғ]|жадынама)/)],
  ['screening', /(?:противопоказан|анкет|проверк|опрос|анализ\S* провер)/,
    kk(/(?:қарсы көрсетілім|сауалнама|алдындағы тексеру|тексеруді (?:бастау|бастайық|жалғастыр)|тексеруден өтейін|тексеруден өту|қауіпсіздік сұрақ)/)],
  ['status', /(?:статус|что дальше|где я|что осталось|мой визит|когда (?:у меня )?(?:мрт|визит|запись))/,
    kk(/(?:мәртебе|не қалды|келесі қадам|әрі қарай не|маршрут|менің жазылу|(?:мрт|тексеру|жазылу|визит)\S*\s+қашан|қашан (?:келу|бару|келемін|барамын)|қай күні)/)],
  ['menu', /^(?:меню|начать|старт|помощь|что ты умеешь|что умеешь)$/,
    kk(/^(?:мәзір|бастау|көмек|не істей аласыз|не білесіз|мүмкіндіктер)$/)],
  ['greeting', /^(?:привет|здравствуй\S*|добрый (?:день|вечер|утро)|салам\S*|hi|hello)/,
    kk(/^(?:сәлем\S*|сәлеметсіз\S*|қайырлы (?:күн|таң|кеш)|армысыз|ассалау\S*|амансыз ба|қалыңыз қалай|қалайсыз)/)],
  ['thanks', /(?:спасибо|благодарю|рахмет)/,
    kk(/(?:рақмет|рахмет|рахмат|алғыс)/)],
];

const RU_Q = /^(?:можно|нужно|надо|как|что|почему|зачем|сколько|когда|где|а если|больно|опасно)/;
const KK_Q_START = kk(/^(?:қалай|не |неге|неліктен|не үшін|қашан|қайда|қай |қанша|кім|бола ма|болады ма|мүмкін бе|рұқсат па|рас па|шынымен)/);
// Вопросительные частицы: «бола ма», «дайын ба», «керек пе». Голосовой ввод часто без «?».
const KK_Q_PARTICLE = kk(/(?:^|\s)(?:ма|ме|ба|бе|па|пе)(?:\s|$)/);

/** Похоже ли на вопрос (русский: «?» и вопросительные слова; казахский: ещё и частицы ма/ме/ба/бе/па/пе). */
export function isQuestion(text: string): boolean {
  if (/\?\s*$/.test(text.trim())) return true;
  const t = norm(text);
  if (RU_Q.test(t)) return true;
  if (detectLang(text) === 'ru') return false;
  const f = foldKk(t);
  return KK_Q_START.test(f) || KK_Q_PARTICLE.test(f);
}

export function detectIntent(text: string): Intent {
  const t = norm(text);
  const f = kkNorm(text);
  for (const [intent, ru, kkRe] of INTENTS) if (ru.test(t) || kkRe.test(f)) return intent;
  if (isQuestion(text)) return 'question';
  return 'unknown';
}
