// Слой безопасности диалога. Работает ДО и ПОСЛЕ LLM и не зависит от неё.
// Шаблоны на русском и казахском проверяются всегда, независимо от языка интерфейса.

import type { Lang } from '../../shared/i18n';
import { foldKk } from './nlu';

/** Казахский шаблон сравнивается со «свёрнутым» текстом (қ→к, ә→а, і→и…): так ловится ввод без казахской раскладки. */
const kk = (re: RegExp) => new RegExp(foldKk(re.source), re.flags);
const kkText = (t: string) => foldKk(t.toLowerCase());

// Экстренные симптомы в сообщении пациента → немедленно показываем 103/112.
const EMERGENCY = [
  /не могу дышать|задыха|трудно дышать|удушь/i,
  /отек(?:ает|ло)? (?:горл|язык|лиц)|отёк(?:ает|ло)? (?:горл|язык|лиц)|опух(?:ло|ает) (?:горл|язык|лиц)/i,
  /бол[ьи] в груди|давит в груди|жжёт в груди|жжет в груди/i,
  /потерял[аи]? сознани|обморок|теря(?:ю|ет) сознани/i,
  /судорог|припад/i,
  /онемел[аио]? (?:половин|рук|лиц)|перекосил|не могу говорить|речь нарушен/i,
  /сильнейш[а-яё]* головн[а-яё]* бол|внезапн[а-яё]* сильн[а-яё]* головн/i,
  /покончить с собой|суицид|не хочу жить|убить себя/i,
  /сыпь по всему телу.*(?:после|контраст)|анафилак/i,
];

const EMERGENCY_KK = [
  // дыхание: «дем ала алмаймын», «тыныс алу қиын», «тұншығып барамын», «ауа жетпейді»
  /дем ала алма|дем алу қиын|дем алуым қиын|тыныс ала алма|тыныс алу қиын|тыныс алуым қиын|тұншығ|демім жетпе|ауа жетпе|демігіп/,
  // отёк горла, языка, лица, губ
  /(?:тамағ|тама[қғ]ым|тіл|бет|ерін|ерн|көмей|кеңірдег)\S*\s+(?:\S+\s+)?ісі(?:п|ніп|пті|нді|ді|нген|ген)/,
  // боль/сдавление в груди, в сердце
  /(?:кеуде|жүрег|төс)\S*\s+(?:\S+\s+){0,2}(?:ауыр(?!лық|ма)|қысып|қысылып|шаншы|күйдір|басып тұр)/,
  // потеря сознания
  /есімнен тан|есінен тан|естен тан|есімді жоғалт|талып қал|талып жығыл|талып құла|есінен айырыл/,
  // судороги
  /құрысып|құрысу|құрысты|тырысып|тырысу|талма ұстады/,
  // неврологические признаки: онемение лица/руки, перекос лица, нарушение речи
  /(?:бет|қол|жартысы|денемнің жарты)\S*\s+(?:\S+\s+)?ұйып|бетім қисай|сөйлей алма|тілім күрмел|сөзім бұзыл/,
  // внезапная сильнейшая головная боль
  /(?:кенет|кенеттен|күрт|аяқ астынан)\S*\s+(?:\S+\s+){0,3}бас\S*\s+(?:\S+\s+){0,2}ауы?р(?!ма)|бас\S*\s+(?:\S+\s+)?(?:кенет|кенеттен|күрт|аяқ астынан)\S*\s+(?:\S+\s+)?ауы?р(?!ма)|ең қатты бас ауру|шыдатпай\S* бас|бас\S*\s+(?:\S+\s+)?шыдатпай/,
  // суицидальные мысли
  /өзімді өлтір|өмір сүргім келмей|өзіме қол жұмса|өлгім келеді|асылып өл/,
  // анафилаксия
  /анафилак|(?:бүкіл|барлық) денем\S*\s+(?:\S+\s+)?(?:бөртп|қызар)\S*.*(?:контраст|ине|укол)/,
].map(kk);

export function detectEmergency(text: string): boolean {
  if (EMERGENCY.some(re => re.test(text))) return true;
  const f = kkText(text);
  return EMERGENCY_KK.some(re => re.test(f));
}

