// Запросы, на которые ассистент не отвечает по существу (клинические решения).
const CLINICAL_DECISION = [
  /можно ли (?:мне )?(?:не|отменить|прекратить|бросить|пропустить) (?:пить|принимать|лекарств|таблетк|препарат)/i,
  /отменить (?:лекарств|таблетк|препарат|метформин|инсулин)/i,
  /какой (?:у меня )?диагноз|поставь(?:те)? диагноз|что у меня за болезнь/i,
  /(?:дозировк|сколько мг|какую дозу)/i,
  /у меня рак\??|это рак\??|это опухоль\??|я умру/i,
];

const CLINICAL_DECISION_KK = [
  // «дәріні ішпесем бола ма», «дәрімді тоқтатуға бола ма», «таблетканы қабылдамасам»
  /(?:дәрі|таблетка|препарат|инсулин|метформин)\S*\s+(?:\S+\s+){0,2}(?:ішпесем|ішпеуге|ішпей|тоқтат|қоя тұр|қойып қой|қабылдамасам|қабылдамауға|тастасам|тастауға|өткізіп жіберсем|ауыстыр|азайт|көбейт)/,
  /(?:ішпесем|қабылдамасам|тоқтатсам)\s+(?:\S+\s+)?бола ма/,
  // диагноз
  /диагноз\S*\s+(?:\S+\s+)?(?:қандай|қойыңыз|қойып бер|айтыңыз)|диагнозым не|қандай диагноз|маған не болған|менде қандай ауру|қандай ауруым/,
  // доза
  /қанша (?:мг|миллиграмм|таблетка|доза)|доза\S*/,
  // «бұл қатерлі ісік пе», «менде рак па», «өлемін бе»
  /(?:бұл|менде|маған)\s+(?:\S+\s+)?қатерлі ісік|қатерлі ісік пе|қатерлі ісігім|ісік пе|ісік бар ма|ісігім бар ма|рак па|рак пе|рагым бар ма|өлемін бе|өліп қалам/,
].map(kk);

export function isClinicalDecisionRequest(text: string): boolean {
  if (CLINICAL_DECISION.some(re => re.test(text))) return true;
  const f = kkText(text);
  return CLINICAL_DECISION_KK.some(re => re.test(f));
}

