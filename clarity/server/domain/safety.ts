// Фильтр ответа LLM: запрещённые формулировки заменяются безопасным ответом.
const FORBIDDEN_OUTPUT = [
  /у вас (?:рак|опухоль|инсульт|рассеянный склероз|аневризма)/i,
  /(?:вам|вы) (?:можно|можете|нужно|стоит) (?:не принимать|отменить|прекратить|бросить)/i,
  /\d+\s?(?:мг|mg|мл)(?![а-яёa-z]).*(?:принимайте|примите|выпейте)/i,
  /(?:допуск|допущены|разрешено|противопоказаний нет|вам можно контраст)/i,
  /(?:не о чем беспокоиться|всё точно в порядке|это точно не|волноваться не стоит)/i,
  /я (?:ваш )?врач|как врач/i,
];

const FORBIDDEN_OUTPUT_KK = [
  // диагноз: «сізде ісік бар», «сізде инсульт жоқ»
  /сізде (?:\S+\s+)?(?:ісік|рак|инсульт|шашыраңқы склероз|склероз|аневризма)/,
  // отмена лекарств: «дәріні тоқтата аласыз», «ішпесеңіз де болады»
  /тоқтата аласыз|тоқтатуға болады|тоқтатыңыз|ішпесеңіз (?:де )?болады|ішпеуіңізге болады|ішпеуге болады|қабылдамауға болады|қабылдамасаңыз (?:де )?болады|ішпей-ақ қой/,
  // дозировки
  /\d+\s?(?:мг|mg|мл)(?![а-яёa-zәғқңөұүһі]).*(?:ішіңіз|қабылдаңыз|ішу керек|қабылдау керек)/,
  // допуск к контрасту: «контраст салуға болады», «қарсы көрсетілім жоқ»
  /контраст\S*\s+(?:\S+\s+)?(?:салуға|енгізуге|жасауға|алуға) болады|сізге контраст болады|рұқсат етілді|рұқсат берілді|қарсы көрсетілім(?:дер)? жоқ|қарсы көрсетілімі(?:ңіз)? жоқ/,
  // ложные заверения
  /бәрі жақсы болады|алаңдайтын ештеңе жоқ|уайымдайтын ештеңе жоқ|қорқатын ештеңе жоқ|бәрі міндетті түрде жақсы|бұл міндетті түрде (?:қауіпсіз|жақсы)/,
  // выдаёт себя за врача или человека
  /мен (?:сіздің )?дәрігермін|дәрігер ретінде (?:айтамын|кеңес беремін)|мен (?:тірі )?адаммын/,
].map(kk);

export function violatesOutputPolicy(text: string): boolean {
  if (FORBIDDEN_OUTPUT.some(re => re.test(text))) return true;
  const f = kkText(text);
  return FORBIDDEN_OUTPUT_KK.some(re => re.test(f));
}

/** Простейшая маскировка персональных данных перед отправкой в модель/логи. */
export function redactPII(text: string): string {
  return text
    .replace(/\+?\d[\d\s()-]{8,}\d/g, '[телефон]')
    .replace(/[\w.+-]+@[\w-]+\.[\w.]+/g, '[email]')
    .replace(/\b\d{12}\b/g, '[ИИН]');
}
